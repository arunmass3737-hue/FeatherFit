<!-- Shared Global UI Script -->
<script>
    // Initialize AOS
    document.addEventListener('DOMContentLoaded', function() {
        AOS.init({
            duration: 700,
            easing: 'ease-out-cubic',
            once: true,
            offset: 40
        });
        if (window.lucide) {
            lucide.createIcons();
        }
        updateDrawerBadges();
    });

    function toggleMobileMenu() {
        const drawer = document.getElementById('mobile-menu-drawer');
        if (drawer) {
            drawer.classList.toggle('-translate-x-full');
        }
    }

    function openSizeGuideModal() {
        const modal = document.getElementById('size-guide-modal');
        if (modal) {
            modal.classList.remove('hidden');
            modal.classList.add('flex');
        }
    }

    function closeSizeGuideModal() {
        const modal = document.getElementById('size-guide-modal');
        if (modal) {
            modal.classList.remove('flex');
            modal.classList.add('hidden');
        }
    }

    function openCartDrawer() {
        const drawer = document.getElementById('cart-drawer-overlay');
        if (drawer) {
            renderCartDrawer();
            drawer.classList.remove('translate-x-full');
        }
    }

    function closeCartDrawer() {
        const drawer = document.getElementById('cart-drawer-overlay');
        if (drawer) {
            drawer.classList.add('translate-x-full');
        }
    }

    function openWishlistDrawer() {
        const drawer = document.getElementById('wishlist-drawer-overlay');
        if (drawer) {
            renderWishlistDrawer();
            drawer.classList.remove('translate-x-full');
        }
    }

    function closeWishlistDrawer() {
        const drawer = document.getElementById('wishlist-drawer-overlay');
        if (drawer) {
            drawer.classList.add('translate-x-full');
        }
    }

    function showToast(message, type = 'success') {
        const container = document.getElementById('php-toast-container');
        if (!container) return;
        const toast = document.createElement('div');
        toast.className = `p-4 rounded-xl text-xs font-semibold backdrop-blur-md shadow-2xl border flex items-center gap-2 transform transition-all duration-300 pointer-events-auto ${
            type === 'success' ? 'bg-purple-950/90 text-purple-200 border-purple-500/40 shadow-glow-sm' : 'bg-gray-900/90 text-gray-200 border-white/10'
        }`;
        toast.innerHTML = `<span>${message}</span>`;
        container.appendChild(toast);
        setTimeout(() => {
            toast.style.opacity = '0';
            toast.style.transform = 'translateY(10px)';
            setTimeout(() => toast.remove(), 300);
        }, 3500);
    }

    function handleFooterSubscribe(e) {
        e.preventDefault();
        const input = document.getElementById('php-footer-newsletter-email');
        if (!input) return;
        const email = input.value.trim().toLowerCase();
        if (!email || !email.includes('@')) return;

        let subscribers = [];
        try {
            subscribers = JSON.parse(localStorage.getItem('ff_newsletter_subscribers') || '[]');
        } catch (err) {}

        const exists = subscribers.some(s => (typeof s === 'string' ? s : s.email) === email);
        if (exists) {
            showToast('You are already subscribed to Feather Fits VIP alerts! ✨', 'info');
        } else {
            subscribers.push({ email, date: new Date().toISOString() });
            localStorage.setItem('ff_newsletter_subscribers', JSON.stringify(subscribers));
            showToast('🎉 Welcome to VIP! You will receive limited drop alerts.', 'success');
        }
        input.value = '';
    }

    function updateDrawerBadges() {
        let cart = [];
        let wishlist = [];
        try {
            cart = JSON.parse(localStorage.getItem('feather_cart') || localStorage.getItem('cart') || '[]');
            wishlist = JSON.parse(localStorage.getItem('feather_wishlist') || '[]');
        } catch(e){}

        const cartBadge = document.getElementById('nav-cart-count');
        if (cartBadge) {
            const count = cart.reduce((acc, it) => acc + (it.quantity || 1), 0);
            if (count > 0) {
                cartBadge.innerText = count;
                cartBadge.classList.remove('hidden');
            } else {
                cartBadge.classList.add('hidden');
            }
        }

        const wishBadge = document.getElementById('nav-wishlist-count');
        if (wishBadge) {
            if (wishlist.length > 0) {
                wishBadge.innerText = wishlist.length;
                wishBadge.classList.remove('hidden');
            } else {
                wishBadge.classList.add('hidden');
            }
        }
    }

    function renderCartDrawer() {
        const container = document.getElementById('cart-drawer-items');
        const totalEl = document.getElementById('cart-drawer-total');
        if (!container) return;

        let cart = [];
        try {
            cart = JSON.parse(localStorage.getItem('feather_cart') || localStorage.getItem('cart') || '[]');
        } catch(e){}

        if (cart.length === 0) {
            container.innerHTML = `
                <div class="text-center py-16 text-gray-500">
                    <i data-lucide="shopping-bag" class="w-12 h-12 mx-auto mb-3 text-gray-600"></i>
                    <p class="text-sm">Your shopping bag is empty.</p>
                </div>
            `;
            if (totalEl) totalEl.innerText = '₹0';
            if (window.lucide) lucide.createIcons();
            return;
        }

        let total = 0;
        let html = '';
        cart.forEach((it, idx) => {
            const price = Number(it.price || 999);
            const qty = Number(it.quantity || 1);
            total += price * qty;
            html += `
                <div class="flex items-center gap-3 p-3 bg-white/[0.02] border border-white/5 rounded-xl">
                    <img src="${it.image || 'assets/hero-bg.webp'}" class="w-14 h-16 object-cover rounded-lg bg-black" />
                    <div class="flex-1 min-w-0">
                        <h4 class="text-xs font-bold text-white truncate">${it.name || 'Apparel'}</h4>
                        <div class="text-[11px] text-gray-400 mt-0.5">Size: ${it.size || 'M'} | Qty: ${qty}</div>
                        <div class="text-xs font-bold text-purple-400 mt-1">₹${(price * qty).toLocaleString('en-IN')}</div>
                    </div>
                    <button type="button" onclick="removeFromCart(${idx})" class="p-1.5 text-gray-500 hover:text-red-400 rounded-lg hover:bg-white/5 transition">
                        <i data-lucide="trash-2" class="w-4 h-4"></i>
                    </button>
                </div>
            `;
        });
        container.innerHTML = html;
        if (totalEl) totalEl.innerText = '₹' + total.toLocaleString('en-IN');
        if (window.lucide) lucide.createIcons();
    }

    function removeFromCart(index) {
        try {
            let cart = JSON.parse(localStorage.getItem('feather_cart') || localStorage.getItem('cart') || '[]');
            cart.splice(index, 1);
            localStorage.setItem('feather_cart', JSON.stringify(cart));
            localStorage.setItem('cart', JSON.stringify(cart));
            renderCartDrawer();
            updateDrawerBadges();
            showToast('Item removed from bag');
        } catch (e) {}
    }

    function renderWishlistDrawer() {
        const container = document.getElementById('wishlist-drawer-items');
        if (!container) return;

        let wishlist = [];
        try {
            wishlist = JSON.parse(localStorage.getItem('feather_wishlist') || '[]');
        } catch(e){}

        if (wishlist.length === 0) {
            container.innerHTML = `
                <div class="text-center py-16 text-gray-500">
                    <i data-lucide="heart" class="w-12 h-12 mx-auto mb-3 text-gray-600"></i>
                    <p class="text-sm">Your wishlist is empty.</p>
                </div>
            `;
            if (window.lucide) lucide.createIcons();
            return;
        }

        let html = '';
        wishlist.forEach((it, idx) => {
            html += `
                <div class="flex items-center gap-3 p-3 bg-white/[0.02] border border-white/5 rounded-xl">
                    <img src="${it.image || 'assets/hero-bg.webp'}" class="w-14 h-16 object-cover rounded-lg bg-black" />
                    <div class="flex-1 min-w-0">
                        <h4 class="text-xs font-bold text-white truncate">${it.name || 'Apparel'}</h4>
                        <div class="text-xs font-bold text-purple-400 mt-1">₹${Number(it.price || 999).toLocaleString('en-IN')}</div>
                    </div>
                    <button type="button" onclick="removeFromWishlist(${idx})" class="p-1.5 text-gray-500 hover:text-red-400 rounded-lg hover:bg-white/5 transition">
                        <i data-lucide="x" class="w-4 h-4"></i>
                    </button>
                </div>
            `;
        });
        container.innerHTML = html;
        if (window.lucide) lucide.createIcons();
    }

    function removeFromWishlist(index) {
        try {
            let wishlist = JSON.parse(localStorage.getItem('feather_wishlist') || '[]');
            wishlist.splice(index, 1);
            localStorage.setItem('feather_wishlist', JSON.stringify(wishlist));
            renderWishlistDrawer();
            updateDrawerBadges();
            showToast('Item removed from wishlist');
        } catch(e){}
    }

    function addToCartDirect(id, name, price, image) {
        let cart = [];
        try {
            cart = JSON.parse(localStorage.getItem('feather_cart') || localStorage.getItem('cart') || '[]');
        } catch(e){}

        const existing = cart.find(it => it.id === id);
        if (existing) {
            existing.quantity = (existing.quantity || 1) + 1;
        } else {
            cart.push({
                id,
                name,
                price: Number(price),
                image,
                size: 'M',
                quantity: 1
            });
        }
        localStorage.setItem('feather_cart', JSON.stringify(cart));
        localStorage.setItem('cart', JSON.stringify(cart));
        updateDrawerBadges();
        showToast(`✓ Added "${name}" to shopping bag!`, 'success');
        openCartDrawer();
    }
</script>
